data class AppUiText(
    val languageName: String,
    val settings: String,
    val appearance: String,
    val theme: String,
    val colors: String,
    val library: String,
    val language: String,
    val useGameBackground: String,
    val useGameBackgroundDescription: String,
    val close: String,
    val restoreDefault: String,
    val information: String,
    val systemTheme: String,
    val lightTheme: String,
    val darkTheme: String,
    val materialYou: String,
    val materialYouDescription: String,
    val viewMode: String,
    val grid: String,
    val list: String,
    val compactGrid: String,
    val categories: Map<String, String>,
    val categoryDescriptions: Map<String, String>,
    val settingTitles: Map<String, String>,
    val settingDescriptions: Map<String, String>,
    val optionLabels: Map<String, String>,
    val ui: Map<String, String>,
    private val keyWords: Map<String, String>,
) {
    private val isEnglish: Boolean
        get() = keyWords.isEmpty()

    fun categoryTitle(key: String): String {
        val title = categories[key]
        val englishTitle = EnglishText.categories[key]
        return cleanText(
            if (!isEnglish && title != null && title == englishTitle) localizedKey(key) else title
                ?: localizedKey(key),
        )
    }

    fun categoryDescription(key: String): String {
        val description = categoryDescriptions[key]
        val englishDescription = EnglishText.categoryDescriptions[key]
        return cleanText(
            (if (!isEnglish && description != null && description == englishDescription) null else description)
                ?: when {
                    this === PortugueseText -> "Opções de ${categoryTitle(key)}"
                    this === SpanishText -> "Opciones de ${categoryTitle(key)}"
                    else -> "${categoryTitle(key)} options"
                },
        )
    }

    fun settingTitle(key: String): String {
        val title = settingTitles[key]
        val englishTitle = EnglishText.settingTitles[key]
        return cleanText(
            if (!isEnglish && title != null && title == englishTitle) localizedKey(key) else title
                ?: localizedKey(key),
        )
    }

    fun settingDescription(key: String): String {
        val description = settingDescriptions[key]
        val englishDescription = EnglishText.settingDescriptions[key]
        return cleanText(
            (if (!isEnglish && description != null && description == englishDescription) null else description)
                ?: when {
                    this === PortugueseText -> "Configuração avançada do emulador (${settingTitle(key)})."
                    this === SpanishText -> "Configuración avanzada del emulador (${settingTitle(key)})."
                    else -> "Advanced emulator setting (${settingTitle(key)})."
                },
        )
    }

    fun optionLabel(value: String): String {
        val label = optionLabels[value]
        val englishLabel = EnglishText.optionLabels[value]
        return cleanText(
            if (!isEnglish && !value.isTechnicalOption() && label != null && label == englishLabel) {
                localizedValue(value)
            } else {
                label
            }
                ?: localizedValue(value),
        )
    }

    fun text(value: String): String = cleanText(ui[value] ?: ui[cleanText(value)] ?: value)

    private fun localizedKey(key: String): String =
        key.replace('-', '_')
            .split('_')
            .filter { it.isNotBlank() }
            .joinToString(" ") { token ->
                keyWords[token.lowercase()] ?: token.replaceFirstChar { it.uppercase() }
            }

    private fun localizedValue(value: String): String {
        val normalized = value.replace('-', '_').replace(' ', '_')
        val translated = localizedKey(normalized)
        return translated.ifBlank { value }
    }
}

private fun cleanText(value: String): String {
    if (value.none { it == 'Ã' || it == 'Â' || it == 'â' || it == '�' }) {
        return value
    }
    return runCatching {
        val candidate = String(value.toByteArray(Charsets.ISO_8859_1), Charsets.UTF_8)
        if (candidate.countMojibakeMarkers() <= value.countMojibakeMarkers()) candidate else value
    }.getOrDefault(value)
}

private fun String.countMojibakeMarkers(): Int =
    count { it == 'Ã' || it == 'Â' || it == 'â' || it == '�' }

private fun String.isTechnicalOption(): Boolean =
    startsWith("x64-") || this in setOf("ASMJIT", "LSFG", "Mailbox", "Fifo", "FIFO", "Immediate")

fun appUiText(language: AppLanguage): AppUiText = when (language) {
    AppLanguage.PORTUGUESE -> PortugueseText
    AppLanguage.SPANISH -> SpanishText
    AppLanguage.ENGLISH -> EnglishText
}

